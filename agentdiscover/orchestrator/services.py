def ensure_all(problem: str, backend: str, only: str = "all") -> None:
    if only in ("all", "neo4j"):
        print(ensure_neo4j(problem, backend))
        db.wait_until_ready()
        n = db.apply_schema()
        print(f"neo4j: schema applied ({n} statements)")
        # Publish the run's settings before anything reads them. This is the only place
        # the environment is consulted; every process reads them from the database.
        values = runconfig.publish(problem)
        summary = runconfig.summary(values)
        # Report the timeout actually enforced; the launcher may raise the stored value.
        effective = runconfig.required_agent_timeout(problem)
        configured = int(values["agent_timeout"])
        if effective != configured:
            summary = summary.replace(
                f"agent_timeout={configured}",
                f"agent_timeout={effective} (raised from {configured})")
        print(f"config: {summary}")
    if only in ("all", "service"):
        print(ensure_service(problem, backend))
    if only == "all":
        # Build the evaluation environment now, so a failure stops the run here. Gated on
        # "all" because it needs the RunConfig published above to resolve the image.
        from ..server import evaluator
        print(evaluator.prepare(problem, backend))


def main() -> None:
    parser = argparse.ArgumentParser(prog="agentdiscover.orchestrator.services")
    sub = parser.add_subparsers(dest="cmd", required=True)
    for cmd in ("ensure", "stop", "status", "reset"):
        p = sub.add_parser(cmd)
        p.add_argument("--problem", required=True)
        p.add_argument("--backend", default=None)
        if cmd == "ensure":
            p.add_argument("--only", choices=("all", "neo4j", "service"), default="all")
    args = parser.parse_args()
    backend = args.backend or sandbox.detect_backend()

    if args.cmd == "ensure":
        ensure_all(args.problem, backend, args.only)
    elif args.cmd == "reset":
        reset(args.problem, backend)
    elif args.cmd == "stop":
        stop_service(args.problem)
        stop_neo4j(args.problem, backend)
        print("stopped.")
    elif args.cmd == "status":
        print("backend:", backend)
        print("bolt answering:", _bolt_answers())
        print("service health:", _health())


if __name__ == "__main__":
    main()
