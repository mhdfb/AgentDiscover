# Run state that reset archives. Caches (eval-data/, eval-deps/, runs/.images/) are
# deliberately not listed and are left alone.
_RUN_STATE = ("neo4j-data", "neo4j-conf", "neo4j-logs", "meta-logs", "run.log",
              "service.log", "neo4j-console.log", "service.fingerprint",
              "meta-pass.json", "STOP", "neo4j.pid", "service.pid")


def reset(problem: str, backend: str) -> None:
    """Archive this problem's run state so the next run starts from iteration 1.
    The state is moved to runs/_archive/<problem>-<stamp>/, never deleted."""
    rd = config.runs_dir(problem)
    if not rd.exists():
        print(f"reset: nothing to archive for {problem} — starting fresh")
        return

    # Stop the services first: they hold neo4j-data/ open.
    stop_service(problem)
    stop_neo4j(problem, backend)

    targets = [rd / n for n in _RUN_STATE] + sorted(rd.glob("agent-*"))
    targets = [p for p in targets if p.exists()]
    if not targets:
        print(f"reset: nothing to archive for {problem} — starting fresh")
        return

    dest = config.repo_root() / "runs" / "_archive" / \
        f"{problem}-{time.strftime('%Y%m%d-%H%M%S')}"
    dest.mkdir(parents=True)
    for path in targets:
        path.rename(dest / path.name)
    print(f"reset: archived {len(targets)} item(s) to {dest.relative_to(config.repo_root())}")
    print("reset: caches kept (eval-data/, eval-deps/, runs/.images/)")


