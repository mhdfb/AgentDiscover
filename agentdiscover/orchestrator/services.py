def _health() -> dict | None:
    try:
        with urllib.request.urlopen(f"{config.service_url()}/health", timeout=2) as resp:
            return json.loads(resp.read().decode())
    except (urllib.error.URLError, OSError, ValueError):
        return None


def _code_fingerprint() -> str:
    """A hash of the service's own source, to detect a service started from older code."""
    h = hashlib.sha256()
    for path in sorted((config.repo_root() / "agentdiscover").rglob("*.py")):
        h.update(path.relative_to(config.repo_root()).as_posix().encode())
        h.update(path.read_bytes())
    return h.hexdigest()


def ensure_service(problem: str, backend: str) -> str:
    rd = config.runs_dir(problem)
    rd.mkdir(parents=True, exist_ok=True)
    fingerprint = _code_fingerprint()
    stamp = rd / "service.fingerprint"
    health = _health()
    if health is not None:
        if health.get("problem") != problem:
            raise SystemExit(
                f"An MCP service for problem {health.get('problem')!r} already holds port "
                f"{config.SERVICE_PORT}. One problem per host at a time — stop it first "
                f"(python -m agentdiscover.orchestrator.services stop --problem {health.get('problem')}) "
                f"or set AGENTDISCOVER_PORT/NEO4J_PORT to run this problem on other ports."
            )
        if stamp.exists() and stamp.read_text().strip() == fingerprint:
            return "service: already running"
        # Same problem, different code: restart. Safe: ensure runs before any agent.
        stop_service(problem)
        time.sleep(1.0)

    log = open(rd / "service.log", "ab")
    proc = subprocess.Popen(
        [sys.executable, "-m", "agentdiscover.server.app", "--problem", problem, "--backend", backend],
        stdout=log, stderr=log, start_new_session=True,
        env={**os.environ, "AGENTDISCOVER_ROOT": str(config.repo_root())},
    )
    (rd / "service.pid").write_text(str(proc.pid))

    deadline = time.monotonic() + 60
    while time.monotonic() < deadline:
        if _health() is not None:
            stamp.write_text(fingerprint)
            return f"service: started (pid {proc.pid}, http://127.0.0.1:{config.SERVICE_PORT})"
        if proc.poll() is not None:
            break
        time.sleep(0.5)
    raise SystemExit(
        f"MCP service did not become healthy — see {rd / 'service.log'}"
    )


def stop_service(problem: str) -> None:
    pidfile = config.runs_dir(problem) / "service.pid"
    pid = _pidfile_alive(pidfile)
    if pid:
        sandbox.stop_detached(pid)
    pidfile.unlink(missing_ok=True)


