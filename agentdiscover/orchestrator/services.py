# The HTTP connector is disabled: it fails inside a converted SIF and only bolt is needed.
_NEO4J_CONF = """\
# Generated by agentdiscover (services.py) — edit NEO4J_* env vars, not this file.
server.directories.data=/data
server.directories.logs=/logs
server.directories.run=/logs/run
server.default_listen_address=127.0.0.1
server.bolt.listen_address=127.0.0.1:{bolt}
server.http.enabled=false
server.memory.heap.initial_size=512m
server.memory.heap.max_size=1g
server.memory.pagecache.size=512m
dbms.usage_report.enabled=false
# Cap the processor count: Neo4j sizes its event loops from it, and on a many-core node
# they can exhaust the file-descriptor limit.
server.jvm.additional=-XX:ActiveProcessorCount=4
"""


def ensure_neo4j(problem: str, backend: str) -> str:
    """Start the database if it is not running. Returns a one-line status."""
    if backend == "none":
        if not _bolt_answers():
            raise SystemExit(
                "SANDBOX_BACKEND=none: no container is started for Neo4j, so an external "
                f"database must already be listening at {config.neo4j_uri()} — none is."
            )
        return "neo4j: external instance (backend none)"

    rd = config.runs_dir(problem)
    data_dir = rd / "neo4j-data"
    logs_dir = rd / "neo4j-logs"
    # Fresh means no auth store yet, not merely no directory, so a first run that died
    # before setting the password retries that step.
    fresh = not (data_dir / "dbms").exists()
    for d in (data_dir, logs_dir, logs_dir / "run"):
        d.mkdir(parents=True, exist_ok=True)

    name = f"agentdiscover-neo4j-{problem}"
    user, password = config.neo4j_auth()

    if backend in ("docker", "podman"):
        running = subprocess.run(
            [backend, "ps", "-q", "--filter", f"name=^{name}$"],
            capture_output=True, text=True,
        )
        if running.stdout.strip():
            return f"neo4j: already running ({backend} container {name})"
        spec = sandbox.SandboxSpec(
            backend=backend,
            image=config.NEO4J_IMAGE,
            command=[],
            mounts=[
                sandbox.Mount(data_dir, "/data", ro=False),
                sandbox.Mount(logs_dir, "/logs", ro=False),
            ],
            env={
                "NEO4J_AUTH": f"{user}/{password}",
                "NEO4J_server_default__listen__address": "127.0.0.1",
                "NEO4J_server_bolt_listen__address": f"127.0.0.1:{config.NEO4J_BOLT_PORT}",
                "NEO4J_server_http_listen__address": f"127.0.0.1:{config.NEO4J_HTTP_PORT}",
                "NEO4J_dbms_usage__report_enabled": "false",
            },
            network="host",
            name=name,
            extra_args=["-d"],
        )
        subprocess.run(sandbox.build_argv(spec), check=True, capture_output=True, text=True)
        return f"neo4j: started ({backend} container {name}, {'fresh' if fresh else 'existing'} data)"

    # apptainer / singularity / enroot: the image entrypoint needs a writable image, so
    # run `neo4j console` with a generated neo4j.conf and manage it by pidfile.
    pidfile = rd / "neo4j.pid"
    if _pidfile_alive(pidfile):
        return "neo4j: already running (pid " + pidfile.read_text().strip() + ")"
    if _bolt_answers():
        return "neo4j: already running (bolt port answers)"

    conf_dir = rd / "neo4j-conf"
    conf_dir.mkdir(parents=True, exist_ok=True)
    (conf_dir / "neo4j.conf").write_text(_NEO4J_CONF.format(bolt=config.NEO4J_BOLT_PORT))
    image = sandbox.prepare_image(backend, config.NEO4J_IMAGE, _images_cache())
    mounts = [
        sandbox.Mount(data_dir, "/data", ro=False),
        sandbox.Mount(logs_dir, "/logs", ro=False),
        sandbox.Mount(conf_dir, "/conf", ro=True),
    ]
    env = {"NEO4J_CONF": "/conf"}

    if fresh:
        setpw = sandbox.SandboxSpec(
            backend=backend, image=image,
            command=["neo4j-admin", "dbms", "set-initial-password", password],
            mounts=mounts, env=env,
        )
        result = sandbox.run(setpw, wall_seconds=120)
        if result.returncode != 0:
            raise SystemExit(f"neo4j-admin set-initial-password failed:\n{result.stderr[-2000:]}")

    spec = sandbox.SandboxSpec(
        backend=backend, image=image,
        command=["neo4j", "console"],
        mounts=mounts, env=env,
    )
    pid = sandbox.spawn_detached(spec, rd / "neo4j-console.log")
    _pidfile_start(pidfile, pid)
    return f"neo4j: started ({backend} pid {pid}, {'fresh' if fresh else 'existing'} data)"


def stop_neo4j(problem: str, backend: str) -> None:
    name = f"agentdiscover-neo4j-{problem}"
    if backend in ("docker", "podman"):
        subprocess.run([backend, "stop", name], capture_output=True, check=False)
        return
    pidfile = config.runs_dir(problem) / "neo4j.pid"
    pid = _pidfile_alive(pidfile)
    if pid:
        sandbox.stop_detached(pid, grace=30)
    pidfile.unlink(missing_ok=True)


