"""Start the two services: the per-problem Neo4j database and the MCP service.

Safe to repeat:  python -m agentdiscover.orchestrator.services ensure --problem X
Neo4j data persists in runs/<problem>/neo4j-data/; backend "none" needs an external
database at NEO4J_URI. The MCP service is a host process and holds the database password.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

from .. import config, db, runconfig, sandbox

# ---------------------------------------------------------------------------
# Small helpers
# ---------------------------------------------------------------------------


def _images_cache() -> Path:
    return config.repo_root() / "runs" / ".images"


def _pidfile_start(pidfile: Path, pid: int) -> None:
    pidfile.write_text(str(pid))


def _pidfile_alive(pidfile: Path) -> int | None:
    if not pidfile.exists():
        return None
    try:
        pid = int(pidfile.read_text().strip())
    except ValueError:
        return None
    return pid if sandbox.pid_alive(pid) else None


def _bolt_answers() -> bool:
    """Cheap TCP probe of the bolt port — is *something* listening?"""
    import socket

    host_port = config.neo4j_uri().split("://", 1)[1]
    host, port = host_port.rsplit(":", 1)
    try:
        with socket.create_connection((host, int(port)), timeout=2):
            return True
    except OSError:
        return False


